#!/usr/bin/env python3
"""Build the canonical LaTeX manuscript from the reviewed Markdown source."""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "paper" / "int4_attention_manuscript_draft.md"
DEFAULT_OUTPUT = ROOT / "paper" / "int4_attention_manuscript.tex"


def pandoc_fragment(markdown: str, pandoc: str, shift_headings: bool = False) -> str:
    command = [
        pandoc,
        "--from=markdown",
        "--to=latex",
        "--wrap=none",
        "--syntax-highlighting=none",
    ]
    if shift_headings:
        command.append("--shift-heading-level-by=-1")
    result = subprocess.run(
        command,
        input=markdown,
        text=True,
        check=True,
        capture_output=True,
    )
    latex = result.stdout.strip().replace("-\\/-", "--")
    return latex.replace("\\begin{figure}\n", "\\begin{figure}[!htbp]\n")


def fold_figure_captions(markdown: str) -> str:
    """Turn an image plus a following bold Figure caption into one Pandoc figure."""
    lines = markdown.splitlines()
    output: list[str] = []
    index = 0
    image_pattern = re.compile(r"^!\[[^]]*\]\(([^)]+)\)$")
    caption_pattern = re.compile(r"^\*\*Figure\s+(\d+)\.\*\*\s*(.*)$")
    while index < len(lines):
        image_match = image_pattern.match(lines[index])
        if not image_match:
            output.append(lines[index])
            index += 1
            continue

        cursor = index + 1
        if cursor < len(lines) and not lines[cursor]:
            cursor += 1
        if cursor >= len(lines):
            output.append(lines[index])
            index += 1
            continue
        caption_match = caption_pattern.match(lines[cursor])
        if not caption_match:
            output.append(lines[index])
            index += 1
            continue

        caption_parts = [caption_match.group(2)]
        cursor += 1
        while cursor < len(lines) and lines[cursor]:
            caption_parts.append(lines[cursor])
            cursor += 1
        caption = " ".join(caption_parts)
        output.append(f"![{caption}]({image_match.group(1)})")
        output.append("")
        index = cursor + 1 if cursor < len(lines) else cursor
    return "\n".join(output)


def split_manuscript(markdown: str) -> tuple[str, str]:
    abstract_marker = "## Abstract\n"
    body_marker = "## 1. Introduction\n"
    if abstract_marker not in markdown or body_marker not in markdown:
        raise ValueError("Expected Abstract and Introduction headings were not found")
    abstract_start = markdown.index(abstract_marker) + len(abstract_marker)
    body_start = markdown.index(body_marker)
    abstract = markdown[abstract_start:body_start].strip()
    body = markdown[body_start:].strip()
    return abstract, body


def normalize_headings(markdown: str) -> str:
    lines: list[str] = []
    appendix_started = False
    numbered = re.compile(r"^(##+)\s+\d+(?:\.\d+)*\.?\s+(.+)$")
    appendix = re.compile(r"^##\s+Appendix\s+[A-Z]\.\s+(.+)$")
    for line in markdown.splitlines():
        appendix_match = appendix.match(line)
        if appendix_match:
            if not appendix_started:
                lines.extend(["\\appendix", ""])
                appendix_started = True
            lines.append(f"## {appendix_match.group(1)}")
            continue
        numbered_match = numbered.match(line)
        if numbered_match:
            lines.append(f"{numbered_match.group(1)} {numbered_match.group(2)}")
            continue
        lines.append(line)
    return "\n".join(lines)


