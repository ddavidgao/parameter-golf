def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--pandoc", default=shutil.which("pandoc"))
    args = parser.parse_args()
    if not args.pandoc:
        raise SystemExit("pandoc was not found; pass --pandoc /path/to/pandoc")

    markdown = args.source.read_text()
    abstract_md, body_md = split_manuscript(markdown)
    body_md = fold_figure_captions(body_md)
    body_md = normalize_headings(body_md)
    abstract_tex = pandoc_fragment(abstract_md, args.pandoc)
    body_tex = pandoc_fragment(body_md, args.pandoc, shift_headings=True)
    args.output.write_text(latex_document(abstract_tex, body_tex))


if __name__ == "__main__":
    main()
